ALIMENTOS = [
    {
        "id": alimento[0],
        "nome": alimento[1],
        "energia": alimento[2],
        "proteina": alimento[3],
        "lipideos": alimento[4],
        "carboidratos": alimento[5],
        "fibra": alimento[6],
    }
    for alimento in DADOS_ALIMENTOS
]


# ============================================================
# BUSCA DE ALIMENTO PELO NOME EXATO
# ============================================================

def buscar_alimento(nome):
    nome = nome.strip().lower()

    for alimento in ALIMENTOS:
        if alimento["nome"].lower() == nome:
            return alimento

    return None


# ============================================================
# BUSCA APROXIMADA PELO NOME
# ============================================================

def buscar_alimentos(nome):
    nome = nome.strip().lower()

    return [
        alimento
        for alimento in ALIMENTOS
        if nome in alimento["nome"].lower()
    ]


# ============================================================
# BUSCA PELO ID
# ============================================================

def buscar_alimento_id(alimento_id):
    for alimento in ALIMENTOS:
        if alimento["id"] == alimento_id:
            return alimento

    return None

